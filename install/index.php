/**
 * Detect public base URL and rewrite base path.
 */
function install_detect_base(): array
{
    $https = (!empty($_SERVER['HTTPS']) && $_SERVER['HTTPS'] !== 'off')
        || (isset($_SERVER['SERVER_PORT']) && (int) $_SERVER['SERVER_PORT'] === 443)
        || (isset($_SERVER['HTTP_X_FORWARDED_PROTO']) && $_SERVER['HTTP_X_FORWARDED_PROTO'] === 'https');

    $scheme = $https ? 'https' : 'http';
    $host = $_SERVER['HTTP_HOST'] ?? 'localhost';
    $script = str_replace('\\', '/', dirname($_SERVER['SCRIPT_NAME'] ?? ''));
    // /path/install → /path/
    $basePath = rtrim(dirname($script), '/\\');
    if ($basePath === '' || $basePath === '.') {
        $basePath = '';
    }
    $url = $scheme . '://' . $host . ($basePath === '' ? '/' : $basePath . '/');
    $rewriteBase = $basePath === '' ? '/' : $basePath . '/';

    return ['url' => $url, 'rewrite_base' => $rewriteBase];
}

function install_requirements(): array
{
    $checks = [];
    $checks[] = [
        'label' => 'PHP 8.1 oder neuer',
        'ok' => version_compare(PHP_VERSION, '8.1.0', '>='),
        'info' => 'Aktuell: ' . PHP_VERSION,
    ];

    foreach (['pdo', 'pdo_mysql', 'curl', 'mbstring', 'json', 'openssl'] as $ext) {
        $checks[] = [
            'label' => 'Extension: ' . $ext,
            'ok' => extension_loaded($ext),
            'info' => extension_loaded($ext) ? 'geladen' : 'fehlt',
        ];
    }

    $checks[] = [
        'label' => 'config.php beschreibbar',
        'ok' => is_writable(dirname(CONFIG_FILE)) || (is_file(CONFIG_FILE) && is_writable(CONFIG_FILE)),
        'info' => dirname(CONFIG_FILE),
    ];
    $checks[] = [
        'label' => '.htaccess beschreibbar',
        'ok' => is_writable(HTACCESS_FILE) || is_writable(ROOT_DIR),
        'info' => HTACCESS_FILE,
    ];
    $checks[] = [
        'label' => 'SQL-Dump vorhanden',
        'ok' => is_file(SQL_FILE),
        'info' => 'teaspace.sql',
    ];
    $checks[] = [
        'label' => 'Composer Vendor',
        'ok' => is_file(ROOT_DIR . '/vendor/autoload.php'),
        'info' => is_file(ROOT_DIR . '/vendor/autoload.php') ? 'vorhanden' : 'composer install ausführen',
    ];

    return $checks;
}

function install_escape(string $value): string
{
    return str_replace(["\\", "'"], ["\\\\", "\\'"], $value);
}

