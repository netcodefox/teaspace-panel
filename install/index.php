function install_update_htaccess(string $rewriteBase): void
{
    if (!is_file(HTACCESS_FILE)) {
        return;
    }
    $ht = file_get_contents(HTACCESS_FILE);
    if ($ht === false) {
        return;
    }
    if (preg_match('/RewriteBase\s+.+/i', $ht)) {
        $ht = preg_replace('/RewriteBase\s+.+/i', 'RewriteBase ' . $rewriteBase, $ht, 1);
    } else {
        $ht = preg_replace('/RewriteEngine\s+on/i', "RewriteEngine on\n    RewriteBase " . $rewriteBase, $ht, 1);
    }
    file_put_contents(HTACCESS_FILE, $ht);
}

function install_import_sql(PDO $pdo): void
{
    $sql = file_get_contents(SQL_FILE);
    if ($sql === false) {
        throw new RuntimeException('teaspace.sql konnte nicht gelesen werden.');
    }

    // Strip comments / phpMyAdmin meta
    $sql = preg_replace('/^--.*$/m', '', $sql);
    $sql = preg_replace('/\/\*![0-9]{5}.*?\*\//s', '', $sql);

    $pdo->exec('SET FOREIGN_KEY_CHECKS=0');
    $buffer = '';
    foreach (explode(";\n", str_replace("\r\n", "\n", $sql)) as $chunk) {
        $chunk = trim($chunk);
        if ($chunk === '') {
            continue;
        }
        $buffer = $chunk;
        try {
            $pdo->exec($buffer);
        } catch (PDOException $e) {
            // Ignore empty / duplicate noise where possible
            if (stripos($e->getMessage(), 'already exists') === false) {
                throw new RuntimeException('SQL-Fehler: ' . $e->getMessage() . ' — Statement: ' . substr($buffer, 0, 120));
            }
        }
    }
    $pdo->exec('SET FOREIGN_KEY_CHECKS=1');
}

